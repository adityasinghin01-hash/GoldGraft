import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { VerifiedConfigCache, routeExisting } from './switch.mjs';
const d = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const c = new VerifiedConfigCache(d.graft_id, d.key);
assert.equal(c.accept(d.initial, d.now), true);
d.initial.stage_pct = 100;
assert.equal(c.current(d.now).stage_pct, 1);
assert.equal(c.accept(d.older, d.now), false);
assert.equal(c.accept(d.same_version_changed, d.now), false);
assert.equal(c.accept(d.expired, d.now), false);
assert.equal(c.current(d.now).stage_pct, 1);
const returned = c.current(d.now); returned.stage_pct = 100;
assert.equal(c.current(d.now).stage_pct, 1);
assert.equal(c.accept(d.newer, d.now), true);
assert.equal(c.current(d.now).version, 4);
assert.equal(c.current(d.expires), null);
assert.equal(routeExisting('CAPTURE', 'NEW'), 'NEW');
assert.throws(() => routeExisting('REFUND', null));
console.log(JSON.stringify({ cases: 12, failures: [], evidence: 'LOCAL_SYNTHETIC_CACHE' }));
